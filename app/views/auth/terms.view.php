    <h3>Regulamin serwisu TwarzoBlok</h3>
    <p><strong>Obowiązuje od:</strong> <?= date('d.m.Y') ?></p>

    <h4>§1. Postanowienia ogólne</h4>
    <p>Serwis TwarzoBlok (dalej „Serwis") jest portalem społecznościowym
    umożliwiającym użytkownikom nawiązywanie kontaktów i publikowanie treści.
    Korzystanie z Serwisu jest bezpłatne i dobrowolne.</p>

    <h4>§2. Warunki korzystania</h4>
    <ul>
        <li>Użytkownik musi mieć ukończone 13 lat.</li>
        <li>Rejestracja wymaga podania prawdziwych danych.</li>
        <li>Każdy użytkownik może posiadać tylko jedno konto.</li>
        <li>Zabrania się udostępniania danych logowania osobom trzecim.</li>
    </ul>

    <h4>§3. Zasady publikowania treści</h4>
    <ul>
        <li>Zabrania się publikowania treści niezgodnych z prawem polskim i UE.</li>
        <li>Zabrania się nękania, zastraszania i mowy nienawiści.</li>
        <li>Zabrania się publikowania treści naruszających prawa autorskie.</li>
        <li>Operator zastrzega prawo do usunięcia treści naruszających regulamin.</li>
    </ul>

    <h4>§4. Ochrona danych osobowych (RODO)</h4>
    <p>Dane osobowe są przetwarzane w celu świadczenia usług Serwisu.
    Masz prawo do wglądu, poprawiania i usunięcia swoich danych.
    Szczegóły w Polityce Prywatności.</p>

    <h4>§5. Odpowiedzialność</h4>
    <p>Operator nie ponosi odpowiedzialności za treści publikowane przez
    użytkowników. Każdy użytkownik odpowiada za swoje publikacje.</p>

    <h4>§6. Zmiany regulaminu</h4>
    <p>Operator zastrzega prawo do zmiany regulaminu z 14-dniowym
    wyprzedzeniem. Dalsze korzystanie z Serwisu oznacza akceptację zmian.</p>

    <h4>§7. Kontakt</h4>
    <p>W sprawach Serwisu: <a href="mailto:kontakt@twarzoblok.pl">kontakt@twarzoblok.pl</a></p>
